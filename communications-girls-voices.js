function gtgFillTokens(message,tokens={}){
  return String(message).replace(/\{\{(payment|dueDay)\}\}/g,(_,key)=>tokens[key]||`{{${key}}}`);
}

function gtgVoiceMessage(code,character='grace',tokens={}){
  const index=Number(String(code).replace(/^T/,''))-1;
  const library=GTG_VOICE_LIBRARY[character]||GTG_VOICE_LIBRARY.grace;
  return gtgFillTokens(library[index]||'',tokens);
}

